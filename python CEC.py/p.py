# Arithicmetic oprations
a = 10
b = 3
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Exponentiation:", a ** b)


#Relational (Comparison) Operators
x = 10
y = 20
print(x == y)
print(x != y)
print(x > y)
print(x < y)
print(x >= 10)
print(y <= 15)


#Logical Operations
a = True
b = False
print("a and b:", a and b)
print("a or b:", a or b)
print("not a:", not a)


#Assignment Operators
